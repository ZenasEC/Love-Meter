# --- tape / textures -------------------------------------------------------
def tape_wobble(buf, base_ms=1.3, depth_ms=0.55):
    """Wow (slow) + flutter (fast) as a modulated fractional delay."""
    n = len(buf)
    out = [0.0] * n
    base = base_ms * 0.001 * SR
    depth = depth_ms * 0.001 * SR
    step = 64.0
    n_lfo = int(n / step) + 2
    lfo = []
    for k in range(n_lfo):
        t = (k * step) / SR
        lfo.append(0.62 * math.sin(2 * math.pi * 0.6 * t)
                   + 0.38 * math.sin(2 * math.pi * 5.7 * t + 1.1))
    last = len(lfo) - 1
    pos = 0.0
    for i in range(n):
        k = int(pos)
        if k > last:
            k = last
        frac = pos - k
        m = lfo[k] * (1.0 - frac) + lfo[k + 1 if k + 1 <= last else last] * frac
        p = i - (base + depth * m)
        p0 = int(p)
        if p0 < 0:
            out[i] = buf[0] * 0.0
        else:
            f = p - p0
            a = buf[p0]
            b = buf[p0 + 1] if p0 + 1 < n else buf[p0]
            out[i] = a * (1.0 - f) + b * f
        pos += 1.0 / step
    for i in range(n):
        buf[i] = out[i]


def saturate(buf, drive):
    """Gentle tape-style soft clip."""
    for i in range(len(buf)):
        buf[i] = math.tanh(buf[i] * drive)


def lowpass(buf, cutoff, q=0.7):
    """RBJ biquad low-pass -- this is what makes it sound like an old tape."""
    w0 = 2.0 * math.pi * cutoff / SR
    cw = math.cos(w0)
    sw = math.sin(w0)
    alpha = sw / (2.0 * q)
    b0 = (1.0 - cw) * 0.5
    b1 = 1.0 - cw
    b2 = b0
    a0 = 1.0 + alpha
    a1 = -2.0 * cw
    a2 = 1.0 - alpha
    b0 /= a0
    b1 /= a0
    b2 /= a0
    a1 /= a0
    a2 /= a0
    x1 = x2 = y1 = y2 = 0.0
    for i in range(len(buf)):
        x = buf[i]
        y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
        x2 = x1
        x1 = x
        y2 = y1
        y1 = y
        buf[i] = y


def highpass(buf, cutoff, q=0.7):
    """RBJ biquad high-pass -- trims rumble the saturation would expose."""
    w0 = 2.0 * math.pi * cutoff / SR
    cw = math.cos(w0)
    sw = math.sin(w0)
    alpha = sw / (2.0 * q)
    b0 = (1.0 + cw) * 0.5
    b1 = -(1.0 + cw)
    b2 = b0
    a0 = 1.0 + alpha
    a1 = -2.0 * cw
    a2 = 1.0 - alpha
    b0 /= a0
    b1 /= a0
    b2 /= a0
    a1 /= a0
    a2 /= a0
    x1 = x2 = y1 = y2 = 0.0
    for i in range(len(buf)):
        x = buf[i]
        y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
        x2 = x1
        x1 = x
        y2 = y1
        y1 = y
        buf[i] = y


def reverb_send(dry):
    """Four damped comb filters -- a small, dark, dreamy room."""
    n = len(dry)
    wet = [0.0] * n
    for delay_s, fb, damp in ((0.0557, 0.52, 0.30),
                              (0.0689, 0.50, 0.32),
                              (0.0811, 0.48, 0.34),
                              (0.0947, 0.46, 0.36)):
        d = int(delay_s * SR)
        s = 0.0
        for i in range(d, n):
            v = dry[i] + wet[i - d] * fb
            s += damp * (v - s)
            wet[i] = s * 0.20
    return wet


def crackle(buf, density, rng):
    """Vinyl pops: sparse little impulses."""
    n = len(buf)
    for _ in range(int(n * density)):
        pos = rng.randrange(n)
        amp = rng.uniform(0.02, 0.15)
        width = rng.randrange(1, 4)
        for k in range(width):
            if pos + k < n:
                buf[pos + k] += amp * (1.0 - k / width)


def hiss(buf, amount, rng):
    """Low-level filtered tape hiss."""
    y = 0.0
    for i in range(len(buf)):
        y += 0.35 * (rng.uniform(-1.0, 1.0) - y)
        buf[i] += y * amount


# --- assembly --------------------------------------------------------------
def build():
    n = int(TOTAL * SR)
    music = [0.0] * n
    rng = random.Random(SEED)

    # drums (kick times are collected so the music can duck under them)
    kick_times = []
    for b in range(BARS):
        kick(music, at(b, 0.0), 1.00, rng)
        kick(music, at(b, 2.5), 0.70, rng)
        if b % 4 == 3:
            kick(music, at(b, 3.75), 0.52, rng)
        kick_times.append(at(b, 0.0))
        kick_times.append(at(b, 2.5))

        snare(music, at(b, 1.0), 0.80, rng)
        snare(music, at(b, 3.0), 0.88, rng)
        if b % 2 == 1:
            snare(music, at(b, 2.75), 0.20, rng)

        for k in range(8):
            v = (0.30 if k % 2 == 0 else 0.17) * rng.uniform(0.85, 1.12)
            hat(music, at(b, k * 0.5), v, rng)
        if b % 8 == 7:
            hat(music, at(b, 3.5), 0.40, rng, dur=0.11)

    # keys, pad, bass, melody
    for b, name in enumerate(PROG):
        tones = CHORDS[name]
        voice(music, at(b, 0.0), tones, 2.2 * BEAT, 0.26, EP,
              decay=2.3, tail=0.7, attack=0.006, release=0.25)
        voice(music, at(b, 2.5), tones, 0.9 * BEAT, 0.17, EP,
              decay=2.6, tail=0.6, attack=0.006, release=0.20)
        voice(music, at(b, 0.0), tones[:3], BAR, 0.055, PAD,
              decay=0.0, tail=0.25, attack=0.35, release=0.45)
        voice(music, at(b, 0.0), [BASS_ROOT[name]], 2.4 * BEAT, 0.55, BASS,
              decay=1.7, tail=0.5, attack=0.010, release=0.20)
        voice(music, at(b, 2.5), [BASS_ROOT[name]], 1.0 * BEAT, 0.28, BASS,
              decay=2.2, tail=0.4, attack=0.010, release=0.15)

    for bar, beat, midi, dur_b, vel in MELODY:
        voice(music, at(bar, beat), [midi], dur_b * BEAT, vel * 0.30, LEAD,
              decay=1.5, tail=0.9, attack=0.02, release=0.15)

    # sidechain: duck the music a little under every kick (hip-hop breathing)
    duck = [1.0] * n
    for t0 in kick_times:
        i0 = int(t0 * SR)
        span = int(0.30 * SR)
        for j in range(span):
            idx = i0 + j
            if idx >= n:
                break
            g = 0.62 + 0.38 * min(1.0, j / (0.26 * SR))
            if g < duck[idx]:
                duck[idx] = g
    for i in range(n):
        music[i] *= duck[i]

    # tape character
    tape_wobble(music)
    saturate(music, 1.7)
    wet = reverb_send(music)
    for i in range(n):
        music[i] += wet[i] * 0.16
    lowpass(music, 6200.0, 0.7)
    highpass(music, 38.0, 0.7)

    # seamless loop fades (applied to the music only, before the textures)
    fade_in = int(0.25 * SR)
    fade_out = int(0.45 * SR)
    for i in range(fade_in):
        music[i] *= i / fade_in
    for i in range(fade_out):
        music[n - 1 - i] *= i / fade_out

    # dust on top, continuous across the loop point
    trng = random.Random(SEED + 7)
    crackle(music, 0.00016, trng)
    hiss(music, 0.006, trng)

    # final soft clip, then normalise
    for i in range(n):
        music[i] = math.tanh(music[i] * 1.15)
    peak = max(1e-9, max(abs(v) for v in music))
    target = 0.92
    for i in range(n):
        music[i] = music[i] / peak * target
    return music


def write_wav(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, "w") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        frames = bytearray()
        for v in data:
            s = int(max(-1.0, min(1.0, v)) * 32767)
            frames += struct.pack("<h", s)
        w.writeframes(bytes(frames))


