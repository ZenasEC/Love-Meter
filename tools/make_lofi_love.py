"""
Generates assets/lofi-love.wav -- an ORIGINAL lofi love instrumental, composed
and synthesized here from scratch with the Python standard library only.

Slow and dusty: mellow seventh chords on an FM (DX7-style) Rhodes electric
piano, a soft round bass, brushed boom-bap drums, a tape chorus, vinyl crackle
and hiss, and a dark low-pass -- a warm love theme that loops all night.

Because this audio is generated by this script it is 100% original work and
therefore royalty-free / copyright-free: you may bundle, host and share it
freely. Re-run this file to rebuild the track:

    python tools/make_lofi_love.py

Output: assets/lofi-love.wav  (32 kHz, mono, seamless loop)
"""

import math
import os
import random
import struct
import wave

# --- session constants -----------------------------------------------------
SR = 32000                 # sample rate
BPM = 76.0                 # laid-back lofi tempo
BEAT = 60.0 / BPM          # seconds per quarter note
BAR = 4.0 * BEAT           # 4/4 time
BARS = 16
TOTAL = BARS * BAR
SWING = 0.10               # lazy push of the off-beat eighths
SEED = 20240214            # fixed, so the track renders byte-for-byte the same


def hz(midi):
    return 440.0 * (2.0 ** ((midi - 69) / 12.0))


def at(bar, beat):
    """Seconds for a musical position, with the off-beat eighths laid back."""
    t = (bar * 4.0 + beat) * BEAT
    if beat % 1.0 == 0.5:      # an eighth off-beat -> swing it late
        t += SWING * BEAT
    return t


# --- sine wavetable --------------------------------------------------------
# A table lookup instead of math.sin() keeps the long render affordable.
TW = 4096
MASK = TW - 1
SIN = [math.sin(2.0 * math.pi * i / TW) for i in range(TW)]
KB = TW / (2.0 * math.pi)               # radians -> wavetable units, for FM

# --- voices: five-partial amplitude recipes (for bass & pad) ---------------
BASS = (1.00, 0.28, 0.04, 0.00, 0.00)   # round upright-ish bass
PAD = (1.00, 0.20, 0.05, 0.00, 0.00)    # warm sustained pad


def voice(buf, start_s, midis, dur_s, vel, amps,
          decay=2.2, tail=0.9, attack=0.005, release=0.18):
    """Additive voice: plucked when decay > 0, sustained when decay == 0."""
    i0 = int(start_s * SR)
    if i0 < 0 or i0 >= len(buf):
        return
    n = int(min(dur_s + tail, 8.0) * SR)
    if i0 + n > len(buf):
        n = len(buf) - i0
    if n <= 0:
        return
    atk = max(1, int(attack * SR))
    rel = max(1, int(release * SR))
    a1, a2, a3, a4, a5 = amps
    incs = [hz(m) * TW / SR for m in midis]
    phs = [0.0] * len(midis)
    v = vel / len(midis)
    for j in range(n):
        t = j / SR
        env = math.exp(-decay * t) if decay > 0.0 else 1.0
        if j < atk:
            env *= j / atk
        if j > n - rel:
            env *= (n - j) / rel
        s = 0.0
        for k in range(len(incs)):
            ph = phs[k]
            p2 = ph + ph
            p3 = p2 + ph
            p4 = p3 + ph
            p5 = p4 + ph
            s += (a1 * SIN[int(ph) & MASK] + a2 * SIN[int(p2) & MASK]
                  + a3 * SIN[int(p3) & MASK] + a4 * SIN[int(p4) & MASK]
                  + a5 * SIN[int(p5) & MASK])
            ph += incs[k]
            if ph >= TW:
                ph -= TW
            phs[k] = ph
        buf[i0 + j] += s * env * v


# --- FM electric piano -----------------------------------------------------
def rhodes(buf, start_s, midis, dur_s, vel, rng, bright=1.0, tine=1.0,
           decay=None, attack=0.010, release=0.42):
    """A DX7-style FM electric piano: a sine carrier frequency-modulated by a
    sine, with the modulation index decaying faster than the amplitude.

    So each note bites bright (the metallic tine) and then melts into a smooth,
    round body, exactly the way a real Rhodes does. Two details kill the
    'cheap synth' tell: the high partials fade before the low ones, and every
    note starts at a random phase so stacked chords bloom instead of clicking."""
    i0 = int(start_s * SR)
    if i0 < 0 or i0 >= len(buf):
        return
    n = int(min(dur_s + release + 0.6, 9.0) * SR)
    if i0 + n > len(buf):
        n = len(buf) - i0
    if n <= 0:
        return
    atk = max(2, int(attack * SR))
    rel = max(2, int(release * SR))
    v = vel / len(midis)

    for m in midis:
        f = hz(m)
        # higher notes ring shorter, like a real piano
        dec = decay if decay is not None else (2.6 - 0.03 * (m - 54))
        dec = max(0.8, min(3.2, dec))
        # (carrier Hz, mod ratio, index, index-decay s, amp, amp-decay)
        specs = (
            (f, 1.0, 1.55 * bright, 0.55, 0.62, dec),                       # body
            (f, 14.0, 2.30 * bright * tine, 0.09, 0.10 * tine, dec * 2.0),  # tine
        )
        # voice state: [inc_c, inc_m, idx, idx_step, amp, amp_step, pc, pm]
        vs = []
        for (fc, ratio, idx0, tau, amp, adec) in specs:
            vs.append([
                fc * TW / SR, fc * ratio * TW / SR, idx0,
                math.exp(-1.0 / (tau * SR)), amp, math.exp(-adec / SR),
                rng.random() * TW, rng.random() * TW,
            ])
        for j in range(n):
            # raised-cosine attack + release: nothing ever clicks
            e = 1.0
            if j < atk:
                x = j / atk
                e = x * x * (3.0 - 2.0 * x)
            elif j > n - rel:
                x = (n - j) / rel
                e = x * x * (3.0 - 2.0 * x)
            s = 0.0
            for vo in vs:
                pm = vo[7] + vo[1]
                if pm >= TW:
                    pm -= TW
                vo[7] = pm
                idx = vo[6] + vo[2] * SIN[int(pm) & MASK] * KB
                s += SIN[int(idx) & MASK] * vo[4]
                pc = vo[6] + vo[0]
                if pc >= TW:
                    pc -= TW
                vo[6] = pc
                vo[2] *= vo[3]
                vo[4] *= vo[5]
            buf[i0 + j] += s * e * v


# --- drum voices -----------------------------------------------------------
def kick(buf, start_s, vel, rng):
    """Soft round kick with a short pitch drop and a papery click."""
    i0 = int(start_s * SR)
    n = int(0.45 * SR)
    ph = 0.0
    for j in range(n):
        idx = i0 + j
        if idx >= len(buf):
            break
        t = j / SR
        f = 44.0 + 150.0 * math.exp(-40.0 * t)
        ph += f * TW / SR
        if ph >= TW:
            ph -= TW
        click = 0.45 * math.exp(-240.0 * t)
        buf[idx] += SIN[int(ph) & MASK] * (1.0 + click) * math.exp(-8.5 * t) * vel


def snare(buf, start_s, vel, rng):
    """Brushed-style snare: high-passed noise plus a small tom body."""
    i0 = int(start_s * SR)
    n = int(0.28 * SR)
    prev = 0.0
    hp = 0.0
    ph = 0.0
    inc = 188.0 * TW / SR
    for j in range(n):
        idx = i0 + j
        if idx >= len(buf):
            break
        t = j / SR
        noise = rng.uniform(-1.0, 1.0)
        hp = 0.82 * (hp + noise - prev)
        prev = noise
        ph += inc
        if ph >= TW:
            ph -= TW
        body = SIN[int(ph) & MASK] * math.exp(-34.0 * t) * 0.30
        buf[idx] += (hp * 0.62 + body) * math.exp(-15.0 * t) * vel


def hat(buf, start_s, vel, rng, dur=0.06):
    """Closed dusty hi-hat."""
    i0 = int(start_s * SR)
    n = int(dur * SR)
    prev = 0.0
    hp = 0.0
    for j in range(n):
        idx = i0 + j
        if idx >= len(buf):
            break
        t = j / SR
        noise = rng.uniform(-1.0, 1.0)
        hp = 0.90 * (hp + noise - prev)
        prev = noise
        env = math.exp(-52.0 * t) * (1.0 - math.exp(-1500.0 * t))
        buf[idx] += hp * env * vel


