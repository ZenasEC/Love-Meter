PROG = ["Fmaj7", "Am7", "Dm7", "Gm7", "Bbmaj7", "C7", "Am7", "Dm7",
        "Fmaj7", "Am7", "Dm7", "Gm7", "Bbmaj7", "Am7", "Gm7", "C7"]

