"""
Generates assets/cupid-loop.wav -- an ORIGINAL music-box waltz in 3/4,
composed and synthesized here from scratch.

Because this audio is generated by this script it is 100% original work and
therefore royalty-free / copyright-free: you may bundle, host and share it
freely. Re-run this file to regenerate the loop:

    python tools/make_cupid_loop.py

Output: assets/cupid-loop.wav  (32 kHz, mono, seamless loop)
"""

import math
import os
import struct
import wave

SR = 32000            # sample rate
BPM = 108.0           # gentle waltz tempo
BEAT = 60.0 / BPM     # seconds per quarter note
BAR = 3 * BEAT        # 3/4 time
BARS = 16
TOTAL = BARS * BAR


def hz(midi):
    return 440.0 * (2.0 ** ((midi - 69) / 12.0))


# --- music-box voice -------------------------------------------------------
# Additive sine partials with a fast attack and exponential decay.
PARTIALS = [(1, 1.00), (2, 0.48), (3, 0.26), (4, 0.14), (5, 0.07)]


def render_note(buf, start_s, midi, dur_s, vel):
    i0 = int(start_s * SR)
    if i0 >= len(buf):
        return
    ring = max(dur_s, 1.4) + 0.9            # let it ring out
    n = int(min(ring, 3.2) * SR)
    f0 = hz(midi)
    decay = 2.6 + (midi - 60) * 0.05        # high notes die faster
    att = int(0.004 * SR)
    for j in range(n):
        idx = i0 + j
        if idx >= len(buf):
            break
        t = j / SR
        env = math.exp(-decay * t)
        if j < att:
            env *= j / att
        s = 0.0
        for mult, amp in PARTIALS:
            s += amp * math.sin(2.0 * math.pi * f0 * mult * t)
        buf[idx] += s * env * vel


def render_pad(buf, start_s, mids, dur_s, vel):
    """Soft sustained warmth under the melody (slow attack/release)."""
    i0 = int(start_s * SR)
    n = int(dur_s * SR)
    att = int(0.25 * SR)
    rel = int(0.4 * SR)
    for j in range(n):
        idx = i0 + j
        if idx >= len(buf):
            break
        t = j / SR
        env = 1.0
        if j < att:
            env = j / att
        if j > n - rel:
            env = max(0.0, (n - j) / rel)
        s = 0.0
        for m in mids:
            s += math.sin(2.0 * math.pi * hz(m) * t)
        buf[idx] += (s / max(1, len(mids))) * env * vel


# --- the composition -------------------------------------------------------
# Chords: I - V - vi - IV family, the classic "romantic" progression.
CHORDS = {
    "C":  (60, 64, 67, 48),
    "G":  (59, 62, 67, 43),
    "Am": (57, 60, 64, 45),
    "F":  (57, 60, 65, 41),
}
PROG = ["C", "G", "Am", "F",
        "C", "G", "F", "G",
        "C", "G", "Am", "F",
        "F", "G", "C", "C"]

# (bar, beat, midi, dur_beats, velocity)  -- the tune
MELODY = [
    (0, 0, 76, 1.5, 1.00), (0, 1.5, 79, 1.5, 0.85),
    (1, 0, 74, 1.0, 0.95), (1, 1, 76, 1.0, 0.80), (1, 2, 74, 1.0, 0.85),
    (2, 0, 72, 1.5, 0.95), (2, 1.5, 76, 1.5, 0.85),
    (3, 0, 69, 1.0, 0.90), (3, 1, 72, 1.0, 0.85), (3, 2, 77, 1.0, 0.90),
    (4, 0, 76, 1.0, 0.95), (4, 1, 79, 1.0, 0.85), (4, 2, 84, 1.0, 0.90),
    (5, 0, 74, 1.5, 0.90), (5, 1.5, 71, 1.5, 0.80),
    (6, 0, 69, 1.0, 0.90), (6, 1, 72, 1.0, 0.85), (6, 2, 69, 1.0, 0.75),
    (7, 0, 71, 1.0, 0.85), (7, 1, 74, 1.0, 0.85), (7, 2, 79, 1.0, 0.90),
    (8, 0, 76, 1.5, 0.95), (8, 1.5, 79, 1.5, 0.85),
    (9, 0, 74, 1.0, 0.90), (9, 1, 71, 1.0, 0.80), (9, 2, 74, 1.0, 0.85),
    (10, 0, 72, 1.5, 0.90), (10, 1.5, 69, 1.5, 0.80),
    (11, 0, 69, 1.0, 0.90), (11, 1, 72, 1.0, 0.85), (11, 2, 77, 1.0, 0.90),
    (12, 0, 69, 1.0, 0.85), (12, 1, 77, 2.0, 0.90),
    (13, 0, 71, 1.0, 0.85), (13, 1, 79, 2.0, 0.90),
    (14, 0, 76, 1.0, 0.90), (14, 1, 84, 2.0, 0.95),
    (15, 0, 79, 3.0, 0.90),
]


def build():
    n = int(TOTAL * SR)
    dry = [0.0] * n

    for b, chord in enumerate(PROG):
        tones = CHORDS[chord]
        t0 = b * BAR
        render_pad(dry, t0, tones[:3], BAR, 0.075)
        render_note(dry, t0, tones[3], 2.0, 0.55)  # soft bass pluck
        # gentle sparkle arpeggio on the off-beats
        render_note(dry, t0 + BEAT * 1.5, tones[1] + 12, 0.8, 0.16)
        render_note(dry, t0 + BEAT * 2.5, tones[2] + 12, 0.8, 0.13)

    for bar, beat, midi, dur_b, vel in MELODY:
        render_note(dry, bar * BAR + beat * BEAT, midi, dur_b * BEAT, vel)

    # --- light dreamy reverb (4 feedback comb filters) ---
    wet = [0.0] * n
    for delay_s, fb in ((0.031, 0.34), (0.037, 0.30), (0.043, 0.27), (0.051, 0.24)):
        d = int(delay_s * SR)
        for i in range(d, n):
            wet[i] += dry[i] + wet[i - d] * fb

    out = [0.0] * n
    for i in range(n):
        out[i] = dry[i] + wet[i] * 0.28

    # normalize
    peak = max(1e-9, max(abs(v) for v in out))
    target = 0.89
    for i in range(n):
        out[i] = out[i] / peak * target

    # seamless loop fades
    fade_in = int(0.35 * SR)
    fade_out = int(0.9 * SR)
    for i in range(fade_in):
        out[i] *= i / fade_in
    for i in range(fade_out):
        out[n - 1 - i] *= i / fade_out
    return out


def write_wav(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, "w") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        frames = bytearray()
        for v in data:
            s = int(max(-1.0, min(1.0, v)) * 32767)
            frames += struct.pack("<h", s)
        w.writeframes(bytes(frames))


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "assets", "cupid-loop.wav")
    samples = build()
    write_wav(out, samples)
    size = os.path.getsize(out)
    print(f"wrote {out}  ({size/1024:.0f} KB, {TOTAL:.1f}s)")
